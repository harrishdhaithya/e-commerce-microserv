-- Inventory schema, initial version.
--
-- This is the one service in the platform where correctness under concurrency is the
-- whole problem. The constraints below are a safety net; the actual mechanism is
-- optimistic locking on stock_items.version (see StockService).

CREATE TABLE stock_items (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Keyed on SKU, a plain string this service treats as opaque. Deliberately NOT a
    -- foreign key: products live in catalog-service's database, which this service
    -- cannot reach.
    sku               VARCHAR(64)  NOT NULL,

    quantity_on_hand  INTEGER      NOT NULL DEFAULT 0,
    quantity_reserved INTEGER      NOT NULL DEFAULT 0,
    reorder_level     INTEGER      NOT NULL DEFAULT 0,

    updated_at        TIMESTAMP    NOT NULL,

    -- The mechanism. Hibernate appends WHERE version = ? to every update, so the
    -- loser of a concurrent reserve fails instead of overwriting.
    version           INTEGER      NOT NULL DEFAULT 0,

    CONSTRAINT uq_stock_items_sku UNIQUE (sku),

    -- Belt and braces. Optimistic locking is what prevents overselling; these turn a
    -- logic bug into a failed statement rather than negative stock.
    CONSTRAINT ck_stock_on_hand  CHECK (quantity_on_hand >= 0),
    CONSTRAINT ck_stock_reserved CHECK (quantity_reserved >= 0),
    CONSTRAINT ck_stock_reserved_le_on_hand CHECK (quantity_reserved <= quantity_on_hand)
);

CREATE INDEX ix_stock_items_reorder ON stock_items (reorder_level);

CREATE TABLE stock_reservations (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id   VARCHAR(36)  NOT NULL,

    -- The order this reservation is held for. A plain string again - orders live in
    -- order-service.
    order_id    VARCHAR(36)  NOT NULL,
    sku         VARCHAR(64)  NOT NULL,
    quantity    INTEGER      NOT NULL,

    status      VARCHAR(20)  NOT NULL DEFAULT 'HELD',

    -- The backstop for a saga that dies mid-flight. Without expiry, one crashed
    -- checkout holds stock forever.
    expires_at  TIMESTAMP    NOT NULL,
    created_at  TIMESTAMP    NOT NULL,
    version     INTEGER      NOT NULL DEFAULT 0,

    CONSTRAINT uq_stock_reservations_public_id UNIQUE (public_id),
    CONSTRAINT ck_stock_reservations_quantity CHECK (quantity > 0)
);

CREATE INDEX ix_reservations_order  ON stock_reservations (order_id);
CREATE INDEX ix_reservations_sweep  ON stock_reservations (status, expires_at);

-- Append-only. Never updated, never deleted.
--
-- This is what makes "why is this SKU at 3?" answerable six weeks later, and it is
-- also a repair mechanism: current quantity is derivable from the sum of changes if
-- the counters ever drift.
CREATE TABLE stock_ledger (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         VARCHAR(64)  NOT NULL,

    -- Signed: negative takes stock out of circulation, positive returns it.
    change      INTEGER      NOT NULL,

    reason      VARCHAR(30)  NOT NULL,

    -- The reservation or order that caused it, where there is one.
    reference   VARCHAR(36),

    occurred_at TIMESTAMP    NOT NULL
);

CREATE INDEX ix_ledger_sku ON stock_ledger (sku, occurred_at);
